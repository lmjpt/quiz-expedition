function cq(country: string, n: number, prompt: string, choices: [string, string, string, string], explain?: string): ChoiceQuestion {
  return { id: `passport:${country}:${n}`, kind: 'choice', level: 2, subject: 'geo', prompt, choices: [...choices], answerIndex: 0, explain }
}

function country(
  id: string,
  name: string,
  emoji: string,
  continent: Continent,
  x: number,
  y: number,
  capital: string,
  facts: [string, string],
  easy: [string, [string, string, string, string], string?],
  mid: [string, [string, string, string, string], string?],
  capitalWrong: [string, string, string],
): Country {
  return {
    id,
    name,
    emoji,
    continent,
    x,
    y,
    capital,
    facts,
    quiz: [
      cq(id, 1, easy[0], easy[1], easy[2]),
      cq(id, 2, mid[0], mid[1], mid[2]),
      cq(id, 3, `${name}의 수도는?`, [capital, ...capitalWrong]),
    ],
  }
}

