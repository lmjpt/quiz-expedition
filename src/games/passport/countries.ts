export const HOME = { id: 'home', name: '대한민국', emoji: '🏠', x: 858, y: 182 } as const

/** [문장, 보기 4개(정답 먼저), 설명?] */
type Spec = [string, [string, string, string, string], string?]

function cq(country: string, n: number, spec: Spec): ChoiceQuestion {
  return { id: `passport:${country}:${n}`, kind: 'choice', level: 2, subject: 'geo', prompt: spec[0], choices: [...spec[1]], answerIndex: 0, explain: spec[2] }
}

const CONTINENTS_FOR_CHOICES: Continent[] = ['asia', 'europe', 'africa', 'north-america', 'south-america', 'oceania']

/** "어느 대륙?" 보기: 정답 + 다른 대륙 셋 */
function continentChoices(c: Continent): [string, string, string, string] {
  const others = CONTINENTS_FOR_CHOICES.filter((x) => x !== c).slice(0, 3)
  return [CONTINENT_NAME[c], ...others.map((x) => CONTINENT_NAME[x])] as [string, string, string, string]
}

function country(
  id: string,
  name: string,
  emoji: string,
  continent: Continent,
  x: number,
  y: number,
  capital: string,
  facts: [string, string],
  easy: Spec,
  mid: Spec,
  capitalWrong: [string, string, string],
  more: { easy: Spec; hard: Spec },
): Country {
  return {
    id,
    name,
    emoji,
    continent,
    x,
    y,
    capital,
    facts,
    quiz: {
      easy: [cq(id, 1, easy), cq(id, 5, more.easy)],
      mid: [cq(id, 2, mid), cq(id, 4, [`${name}, 어느 대륙에 있을까요?`, continentChoices(continent)])],
      hard: [cq(id, 3, [`${name}의 수도는?`, [capital, ...capitalWrong]]), cq(id, 6, more.hard)],
    },
  }
}

