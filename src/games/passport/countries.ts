// 이야기 두 줄, 그 나라 문제 6개가 있습니다: 쉬움 2, 보통 2(하나는 "어느 대륙?" 자동), 어려움 2(수도 + 하나).
// 여행 문제는 전부 그 나라 문제입니다 — 처음엔 상식 하나를 섞었는데 "그 나라 문제 위주로" 라는 말을 들었습니다.
// 낮은 단계(1~2)는 쉬움+보통에서 3개, 높은 단계는 보통+어려움에서 3개를 매번 섞어 뽑습니다.
// 문제 정답은 항상 첫 보기 (화면에 낼 때 섞습니다). 국기 이모지는 윈도우에서 안 보여서 쓰지 않습니다.
// 나라를 더 넣을 때는 지도(WorldMap.tsx) 대륙 모양 안에 핀이 놓이는지 확인하세요.

import type { ChoiceQuestion } from '../../types'

export type Continent = 'asia' | 'europe' | 'africa' | 'north-america' | 'south-america' | 'oceania' | 'antarctica'

export const CONTINENT_NAME: Record<Continent, string> = {
  asia: '아시아',
  europe: '유럽',
  africa: '아프리카',
  'north-america': '북아메리카',
  'south-america': '남아메리카',
  oceania: '오세아니아',
  antarctica: '남극',
}

export interface Country {
  id: string
  name: string
  emoji: string
  continent: Continent
  x: number
  y: number
  capital: string
  facts: [string, string]
  quiz: { easy: ChoiceQuestion[]; mid: ChoiceQuestion[]; hard: ChoiceQuestion[] }
}

