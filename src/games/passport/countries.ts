export interface Country {
  id: string
  name: string
  emoji: string
  continent: Continent
  x: number
  y: number
  capital: string
  facts: [string, string]
  /** [쉬움, 보통, 수도] */
  quiz: [ChoiceQuestion, ChoiceQuestion, ChoiceQuestion]
}

